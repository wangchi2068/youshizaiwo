/**
 * 评测集（eval scenarios）。
 *
 * 两类场景：
 *  - memory: 多轮剧情中埋入关键事实 → 强制小预算触发上下文压缩 → 压缩后探询，
 *            检查关键事实是否仍被模型记忆（记忆保持率）。
 *  - compression: 长剧情原文 → 旁侧模型压缩 → 计算 token 节省与关键点保持率。
 *
 * 场景均为中文，取材自本作《优势在我》的临床叙事（入院 / 会诊 / 病历 / 夜班）。
 * facts 的 keyword 用于探询命中判定。
 */

export interface Fact {
	/** 探询回复中出现即视为该事实被保持 */
	keyword: string;
	label: string;
}

export interface MemoryScenario {
	id: string;
	name: string;
	turns: string[];
	facts: Fact[];
	probe: string;
}

export interface CompressionScenario {
	id: string;
	name: string;
	narrative: string;
	/** 压缩后摘要中应保留的关键点 */
	mustKeep: string[];
}

